CREATE SCHEMA IF NOT EXISTS MY_NEW_APP;

CREATE TABLE IF NOT EXISTS MY_NEW_APP.CUSTOMERS
(
    ID           BIGSERIAL PRIMARY KEY,
    NAME         VARCHAR(100),
    SURNAME      VARCHAR(100),
    AGE          INTEGER,
    PHONE_NUMBER VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS MY_NEW_APP.ORDERS
(
    ID           BIGSERIAL PRIMARY KEY,
    DATE         DATE,
    CUSTOMER_ID  BIGINT,
    PRODUCT_NAME VARCHAR(200),
    AMOUNT       INTEGER,
    FOREIGN KEY (CUSTOMER_ID) REFERENCES MY_NEW_APP.CUSTOMERS (ID)
);
